"""One record per external source: what it is, what it says about reuse, and
whether we redistribute any of it — per dataset.

WHY THIS FILE EXISTS
--------------------
Ten external sources feed this project and four of them had a licence recorded
anywhere. There was no NOTICE, no ATTRIBUTION file, and no way for a reader to
see whose data they were looking at. That is a problem for a project that might
be shared, and a worse one for a project whose whole argument is that provenance
should be visible.

WHY PER DATASET
---------------
This file was written for breast and said "51 agents" and "brca_tcga_pub" as
literals, so any other cancer that ran it would have shown breast's cohort and
breast's drug count in its own Evidence lens. Each dataset now lists only the
sources it has facts from, with its own counts read off those facts. The terms
themselves (licence, confidence, licence_url) are properties of the source and
stay shared.

WHAT THIS FILE IS NOT
---------------------
Legal advice, and it must not pretend to be. Each record carries a `confidence`:

  stated    the source publishes this term plainly and it is quoted here
  likely    the source's category makes it near-certain (US federal work), but
            the specific page was not read for this project
  verify    a human must read the terms before publishing or redistributing

`verify` is not a placeholder to be quietly upgraded. A term that has not been
read stays `verify` until someone reads it.

REDISTRIBUTION is tracked separately from licence, because it is a different
act. Linking to a structure image and committing a folder of them into the repo
are not the same thing, and only the second needs a notice.
"""
