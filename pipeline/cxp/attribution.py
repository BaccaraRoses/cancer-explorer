BY_ID = {s["id"]: s for s in SOURCES}

DISCLAIMER = ("A record of what each source states, not legal advice. Entries marked "
              "'verify' have not been read for this project and must be before "
              "publishing.")


def _load(path: Path) -> dict | None:
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return None


def _studies(cancer, with_survival: bool) -> list[str]:
    """Every cBioPortal study this dataset's config reads, in declaration order."""
    seen: list[str] = []
    ids = [cancer.study]
    for cn in cancer.cohort_nodes:
        ids.append(cn.study)
        ids.extend(c.study for c in cn.contrasts if c.study)
    if with_survival and cancer.survival_study:
        ids.append(cancer.survival_study)
    for s in ids:
        if s and s not in seen:
            seen.append(s)
    return seen


def for_cancer(cancer, facts_dir: Path, project_dir: Path, research_dir: Path) -> list[dict[str, Any]]:
    """The sources one dataset actually has facts from, worded with its own counts."""
    cid = cancer.id

    def facts(kind: str) -> dict | None:
        return _load(facts_dir / f"{cid}.{kind}.json")

    out: list[dict[str, Any]] = []

    def add(sid: str, **over: Any) -> None:
        rec = dict(BY_ID[sid])
        rec.update({k: v for k, v in over.items() if v is not None})
        out.append(rec)

    overview, incidence = facts("overview"), facts("incidence")
    if overview:
        add("seer", used_for="Incidence, mortality, stage distribution, survival, lifetime risk and "
                             "median age" + ("; per-subtype shares" if incidence else "") + ".")

    molecular, survival, targets = facts("molecular"), facts("survival"), facts("targets")
    if molecular:
        parts = ["alteration frequencies per subtype and per cohort node"]
        if (molecular.get("concordance") or {}).get("available"):
            parts.append("the concordance matrix")
        if targets:
            parts.append("mutation hotspots with protein positions")
        if survival:
            parts.append("survival by subtype")
        studies = _studies(cancer, bool(survival))
        add("cbioportal",
            used_for=(", ".join(parts[:-1]) + " and " + parts[-1] if len(parts) > 1 else parts[0])
                     .capitalize() + ".",
            note=f"Studies read: {', '.join(studies)}. Each carries the terms of its "
                 "originating consortium.")

    if targets:
        add("uniprot", redistributed=f"Domain boundaries and protein names, in data/{cid}.targets.js.")
        images: dict[str, int] = {}
        for g in (targets.get("genes") or {}).values():
            st = (g or {}).get("structure") or {}
            if st.get("image"):
                images[st["image"]] = st.get("image_bytes") or 0
        n_img = len(images)
        add("rcsb", redistributed=(
            f"YES — {n_img} rendered JPEG image{'s' if n_img != 1 else ''} for this dataset under "
            f"data/img/ (~{sum(images.values()) // 1024} KB)." if n_img else
            "No images for this dataset."))
        lab = targets.get("labels_summary") or {}
        if lab.get("n_with_label"):
            add("openfda", used_for=(
                f"Boxed warnings, named warnings and common adverse reactions for "
                f"{lab['n_with_label']} of {lab.get('n_drugs')} agents, from their US labels."))

    civic = facts("civic")
    if civic:
        add("civic", used_for=f"Evidence levels, evidence types and therapy associations per gene, "
                              f"from {civic.get('total_reported')} evidence items.")

    trials = facts("trials")
    if trials:
        add("clinicaltrials", used_for=f"Status, phase, sponsor, enrolment and dates for "
                                       f"{trials.get('n_returned')} trials, joined to the curated drug "
                                       f"rows by NCT id.")

    literature = facts("literature")
    if literature:
        add("europepmc", used_for=f"The Literature lens: {literature.get('n_papers')} papers since "
                                  f"{literature.get('since')} — titles, journals, dates, publication "
                                  f"types, MeSH headings, preprint flags.")

    if facts("gwas"):
        traits = cancer.gwas_trait
        if isinstance(traits, str):
            label = f"the trait '{traits}'"
        else:
            label = "the traits " + ", ".join(f"'{t}'" for t in traits)
        add("gwas", used_for=f"Polygenic risk associations for {label}.")

    oncotree = facts("oncotree")
    if oncotree:
        n = len(oncotree.get("nodes") or {})
        add("oncotree", redistributed=f"Codes and names for {n} node{'s' if n != 1 else ''}.")

    dataset_js = project_dir / "data" / cancer.dataset_js
    text = dataset_js.read_text(encoding="utf-8", errors="replace") if dataset_js.exists() else ""
    if "gco.iarc" in text or "GLOBOCAN" in text:
        add("globocan", redistributed=f"Worldwide figures curated by hand in data/{cid}.js.")

    if cancer.pipeline_csv:
        path = research_dir / cancer.pipeline_csv
        if path.exists():
            with path.open(encoding="utf-8-sig", newline="") as fh:
                n = sum(1 for r in csv.DictReader(fh) if (r.get("drug_name") or "").strip())
            add("pipeline_csv",
                name=f"Curated {cid} drug pipeline",
                used_for=f"{n} agent rows with target, modality, company, phase, trial and readout.",
                redistributed=f"Yes, in data/{cid}.targets.js.")
    return out


def summary(cancer, facts_dir: Path, project_dir: Path, research_dir: Path) -> dict[str, Any]:
    sources = for_cancer(cancer, facts_dir, project_dir, research_dir)
    return {
        "cancer": cancer.id,
        "n_sources": len(sources),
        "needs_verification": [s["id"] for s in sources if s["confidence"] == "verify"],
        "binary_redistribution": [s["id"] for s in sources
                                  if str(s.get("redistributed", "")).lower().startswith("yes")],
        "attribution_required": [s["id"] for s in sources if s.get("attribution_required")],
        "disclaimer": DISCLAIMER,
        "sources": sources,
    }


def render_markdown(summaries: list[dict[str, Any]]) -> str:
    """One file for the whole project: every source any dataset uses, and which."""
    users: dict[str, list[str]] = {}
    for s in summaries:
        for src in s["sources"]:
            users.setdefault(src["id"], []).append(s["cancer"])
    used = [BY_ID[sid] for sid in BY_ID if sid in users]

    out: list[str] = []
    a = out.append
    a("# Attribution and data sources\n")
    a("Generated by `python run.py attribution` from `pipeline/cxp/attribution.py`.")
    a("Edit that file, not this one.\n")
    a("> **This is a record of what each source states about reuse. It is not legal "
      "advice.** Entries marked `verify` have not been read for this project and should "
      "be before publishing or redistributing.\n")

    verify = [s for s in used if s["confidence"] == "verify"]
    if verify:
        a("## Read these before publishing\n")
        for s in verify:
            a(f"- **{s['name']}** — {s['licence']}  ")
            a(f"  {s['licence_url']}")
        a("")

    a("## Every source\n")
    a("| Source | Datasets | Licence as stated | Confidence |")
    a("|---|---|---|---|")
    for s in used:
        a(f"| [{s['name']}]({s['url'] or s['licence_url']}) | {', '.join(users[s['id']])} "
          f"| {s['licence']} | `{s['confidence']}` |")
    a("")

    for summ in summaries:
        a(f"## {summ['cancer']}\n")
        a("| Source | Used for | Copied here? |")
        a("|---|---|---|")
        for src in summ["sources"]:
            a(f"| {src['name']} | {src['used_for']} | {src.get('redistributed') or '—'} |")
        a("")

    a("## Notes\n")
    for s in used:
        if s.get("note"):
            a(f"### {s['name']}\n")
            a(f"{s['note']}\n")
    return "\n".join(out) + "\n"
