/* facts.js — merge the pipeline's computed overlay onto a curated dataset.

   data/<cancer>.facts.js is generated by pipeline/run.py emit and holds only
   numbers that have an explicit numerator and denominator. data/<cancer>.js is
   hand-written and holds judgement. This joins them at boot without either
   file knowing about the other.

   The merge never overwrites a curated figure. It attaches the computed one
   alongside, so a disagreement stays visible instead of being silently
   resolved in favour of whichever file was written last — that visible
   disagreement is the point, and it is what pipeline/reports/<cancer>.audit.md exists
   to chase down.
*/
(function (global) {
  'use strict';

  /* Curated `alteration` is prose ("loss-of-function mutation"); computed
     `metric` is one of four fixed labels. They line up by containment far more
     reliably than by equality, so try that first and fall back to gene
     identity only when the gene is unambiguous. A gene with several computed
     rows and no wording overlap is left unmatched rather than guessed at. */
  function lower(s) { return String(s == null ? '' : s).toLowerCase(); }

  function matchDriver(curated, rows) {
    var gene = lower(curated.gene);
    var same = rows.filter(function (r) { return lower(r.gene) === gene; });
    if (!same.length) return null;

    var alt = lower(curated.alteration);
    if (alt) {
      var exact = same.filter(function (r) { return lower(r.metric) === alt; });
      if (exact.length) return exact[0];
      var overlap = same.filter(function (r) {
        var m = lower(r.metric);
        return m && (alt.indexOf(m) !== -1 || m.indexOf(alt) !== -1);
      });
      if (overlap.length) return overlap[0];
    }
    return same.length === 1 ? same[0] : null;
  }

  function apply(ds, overlays) {
    var all = overlays || global.CancerExplorerFacts || {};
    var overlay = all[ds.id];
    if (!overlay) return null;

    var stats = { nodes: 0, matched: 0, unmatched: 0, coded: 0 };
    var byNode = overlay.nodes || {};
    var codes = (overlay.codes || {}).nodes || {};

    (ds.nodes || []).forEach(function (n) {
      var rec = byNode[n.id];
      if (rec) {
        stats.nodes++;
        n.computed = {
          /* A node's OWN cohort wins. Most nodes are subtypes of the study
             named at the top of the overlay, but a disease-state node is a
             different study entirely — showing castration-resistant figures
             under the primary-tumour cohort's name would misattribute every
             number on the card. */
          cohort: rec.cohort || overlay.cohort || null,
          cohortNote: rec.cohort_note || null,
          /* "Which subtype of this cancer the cohort called this node" —
             once `pam50_label`, after breast's classifier. */
          subtypeLabel: rec.subtype_label,
          nSamples: rec.n_samples,
          nSequenced: rec.n_sequenced,
          nCnaProfiled: rec.n_cna_profiled
        };
        ((n.molecular || {}).drivers || []).forEach(function (d) {
          var m = matchDriver(d, rec.drivers || []);
          if (!m) { stats.unmatched++; return; }
          stats.matched++;
          d.computed = {
            frequency: m.frequency,
            n: m.n,
            of: m.of,
            metric: m.metric,
            delta: typeof d.frequency === 'number' ? +(m.frequency - d.frequency).toFixed(1) : null
          };
        });
      }
      if (codes[n.id]) {
        stats.coded++;
        n.codes = codes[n.id];
      }
    });

    ds.facts = {
      cohort: overlay.cohort || null,
      concordance: overlay.concordance || null,
      survival: overlay.survival || null,
      incidence: overlay.incidence || null,
      // whole-disease figures for the front page — per-subtype `incidence`
      // has never carried them
      overview: overlay.overview || null,
      attribution: overlay.attribution || null,
      polygenic: overlay.polygenic || null,
      civic: overlay.civic || null
    };
    return stats;
  }

  function report(dsId, stats) {
    if (!stats) {
      console.info('[facts] ' + dsId + ': no overlay registered — curated figures only');
      return;
    }
    console.info('[facts] ' + dsId + ': ' + stats.matched + ' driver(s) matched across ' +
      stats.nodes + ' node(s), ' + stats.coded + ' node(s) coded' +
      (stats.unmatched ? ', ' + stats.unmatched + ' unmatched' : ''));
  }

  global.Facts = { apply: apply, report: report, _matchDriver: matchDriver };
})(this);
